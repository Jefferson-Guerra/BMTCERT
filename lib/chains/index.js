// Mapa de cadenas por tipo de validación detectado
const CHAINS = {
  DV: { inter1: DV_INTER1, inter2: COMMON_INTER2, root: COMMON_ROOT },
  OV: { inter1: OV_INTER1, inter2: COMMON_INTER2, root: COMMON_ROOT },
  EV: { inter1: EV_INTER1, inter2: COMMON_INTER2, root: COMMON_ROOT }
};

/**
 * Detecta el tipo de validación (DV/OV/EV) a partir del Issuer (CN del emisor)
 * del certificado hoja. Sectigo emite el CN del emisor como:
 * "Sectigo Public Server Authentication CA DV R36" (o OV / EV)
 */
/**
 * Detecta si el emisor (issuerCN) de un certificado corresponde EXACTAMENTE
 * a uno de los 3 intermedios de Sectigo que la app trae integrados de fábrica.
 *
 * IMPORTANTE: a propósito ya NO se hace una búsqueda de texto suelta
 * buscando " DV ", " OV " o " EV " en cualquier parte del nombre del
 * emisor. Esa versión anterior era un bug: por ejemplo DigiCert tiene una
 * línea de certificados llamada "Encryption Everywhere DV TLS CA", cuyo
 * nombre contiene " DV " sin ser Sectigo en absoluto — lo que hacía que el
 * programa usara por error la cadena de Sectigo para certificados de OTRAS
 * entidades (DigiCert, Let's Encrypt, GoDaddy, etc.).
 *
 * Ahora se exige coincidencia EXACTA con el nombre real del emisor de cada
 * cadena Sectigo integrada, así que esta función solo devuelve DV/OV/EV
 * cuando el certificado es Sectigo de verdad. Para cualquier otra entidad,
 * devuelve null, y el programa pedirá al usuario que agregue los
 * intermediarios/root correspondientes en "Intermediarios".
 */
function detectTypeFromIssuerCN(issuerCN) {
  if (!issuerCN) return null;
  const normalized = issuerCN.trim().toLowerCase();

  for (const tipo of Object.keys(CHAINS)) {
    const subjectCN = getSubjectCN(CHAINS[tipo].inter1);
    if (subjectCN && subjectCN.trim().toLowerCase() === normalized) {
      return tipo;
    }
  }
  return null;
}

/** Extrae el Subject CN (a quién fue emitido) de un certificado PEM, usando node-forge. */
function getSubjectCN(pem) {
  try {
    const cert = forge.pki.certificateFromPem(pem);
    const attr = cert.subject.attributes.find(a => a.shortName === 'CN');
    return attr ? attr.value : null;
  } catch (e) {
    return null;
  }
}

module.exports = { CHAINS, detectTypeFromIssuerCN };
